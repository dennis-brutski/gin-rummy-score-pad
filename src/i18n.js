// Picks the best supported locale code for an explicit setting, or for the
// device's preferences when set to 'auto'.
function resolveLocale(setting) {
  if (setting && setting !== 'auto' && dict[setting]) return setting;
  const nav = (typeof navigator !== 'undefined' && (navigator.languages || [navigator.language])) || ['en'];
  for (const tag of nav) {
    if (!tag) continue;
    const base = String(tag).toLowerCase().split('-')[0];
    if (dict[base]) return base;
  }
  return 'en';
}

// Returns a `t(key, ...args)` lookup bound to a locale. Falls through to
// English, then to the raw key, so a missing translation is at worst a
// developer-facing string rather than a crash.
function makeT(locale) {
  return function t(key, ...args) {
    let val = dict[locale]?.[key];
    if (val === undefined) val = dict.en[key];
    if (val === undefined) return key;
    return typeof val === 'function' ? val(...args) : val;
  };
}

// React context — every screen reads { t, locale, setLocale, localeSetting }.
const LocaleContext = React.createContext({
  t: (k) => k, locale: 'en', setLocale: () => {}, localeSetting: 'auto',
});
const useT = () => React.useContext(LocaleContext);

