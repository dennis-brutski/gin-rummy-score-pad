// Russian plural form picker — 3 buckets (one / few / many) per CLDR.
function pluralRu(n, one, few, many) {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs >= 11 && abs <= 14) return many;
  if (last === 1) return one;
  if (last >= 2 && last <= 4) return few;
  return many;
}

// Sentence-case Roman numerals — used in localised "Deal V" headers.
function romanize(n) {
  const map = [['X',10],['IX',9],['V',5],['IV',4],['I',1]];
  let s = '', k = n;
  for (const [r, v] of map) { while (k >= v) { s += r; k -= v; } }
  return s || 'I';
}

